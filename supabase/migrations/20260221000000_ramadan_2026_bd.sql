  ) as v(ramadan_day, gregorian_date, sehri_end, iftar)
),
division_offsets as (
  select *
  from (
    values
      ('Dhaka', 0, 0),
      ('Chattogram', -5, -4),
      ('Rajshahi', 6, 6),
      ('Khulna', 4, 4),
      ('Barishal', -1, 1),
      ('Sylhet', -8, -8),
      ('Rangpur', 5, 4),
      ('Mymensingh', -1, -1)
  ) as o(division, sehri_offset_min, iftar_offset_min)
)
insert into public.prayer_times (
  division,
  ramadan_day,
  gregorian_date,
  sehri_end,
  iftar,
  tahajjud_recommended
)
select
  o.division,
  b.ramadan_day,
  b.gregorian_date,
  (b.sehri_end + make_interval(mins => o.sehri_offset_min))::time as sehri_end,
  (b.iftar + make_interval(mins => o.iftar_offset_min))::time as iftar,
  ((b.sehri_end + make_interval(mins => o.sehri_offset_min)) - interval '01:00')::time as tahajjud_recommended
from dhaka_base b
cross join division_offsets o
on conflict (division, gregorian_date)
do update set
  ramadan_day = excluded.ramadan_day,
  sehri_end = excluded.sehri_end,
  iftar = excluded.iftar,
  tahajjud_recommended = excluded.tahajjud_recommended,
  updated_at = now();
