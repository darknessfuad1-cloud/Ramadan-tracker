-- Auth: Google (Supabase Auth)
-- DB: profiles, ramadan_progress, prayer_times

create or replace function public.set_updated_at_timestamp()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  division text check (division in ('Dhaka', 'Chattogram', 'Rajshahi', 'Khulna', 'Barishal', 'Sylhet', 'Rangpur', 'Mymensingh')),
  language text not null default 'bn' check (language in ('en', 'bn', 'ar')),
  theme text not null default 'light' check (theme in ('light', 'dark')),
  before_goals jsonb not null default '[]'::jsonb,
  during_goals jsonb not null default '[]'::jsonb,
  review jsonb not null default '{"gains":"","shortcomings":"","nextYearPlan":""}'::jsonb,
  special jsonb not null default '{"iitikafNights":[false,false,false,false,false,false,false,false,false,false],"qadrDuaDone":[false,false,false,false,false,false,false,false,false,false],"eidSunnah":[false,false,false,false,false,false]}'::jsonb,
  global_reflection text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ramadan_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  ramadan_day smallint not null check (ramadan_day between 1 and 30),
  surah_completed boolean not null default false,
  hadith_completed boolean not null default false,
  record jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, ramadan_day)
);

create table if not exists public.prayer_times (
  id bigint generated by default as identity primary key,
  division text not null check (division in ('Dhaka', 'Chattogram', 'Rajshahi', 'Khulna', 'Barishal', 'Sylhet', 'Rangpur', 'Mymensingh')),
  ramadan_day smallint not null check (ramadan_day between 1 and 30),
  gregorian_date date not null,
  sehri_end time not null,
  iftar time not null,
  tahajjud_recommended time not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (division, ramadan_day),
  unique (division, gregorian_date)
);

